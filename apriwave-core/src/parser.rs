//! Positional parser (stage 1).
//!
//! Classification is driven by slot parity: odd = tile, even = glyph.
//! The parser is iterative (no recursion → no stack overflow on hostile
//! input) and **recovers** at block boundaries (Q25): it keeps parsing to
//! collect all diagnostics, but a period with diagnostics does not enter the AST.

use crate::prelude::*;

use core::num::{NonZeroU32, NonZeroU8};

use crate::ast::{
    CaseTile, ClauseBlock, ColonRun, Conjunction, GlyphPath, GlyphSlot, Link, LinkedClause, Pair,
    Period, PeriodClose, PeriodOpen, PortabilityBlock, PortabilityKeyword, RelationalBlock,
    ANAPHORA_MARK,
};
use crate::error::{Diagnostic, DiagnosticKind, Expected, Limit, Severity, WarningCodes};
use crate::glyph::parse_glyph_slot;
use crate::lexer::RawToken;
use crate::span::{Span, Spanned};
use crate::symbol::Interner;
use crate::tiles::{self, SignalParse};
use crate::validate;

/// Default maximum DSP depth (Q13).
pub const DEFAULT_MAX_DSP_DEPTH: NonZeroU8 = NonZeroU8::MIN.saturating_add(63);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ParserConfig {
    /// Maximum number of consecutive `:` (Q13, `ERR_SCOPE` if exceeded).
    pub max_dsp_depth: NonZeroU8,
    /// Maximum `abdur=<N>` count and maximum number of execution-plan steps
    /// generated by (nested) loops (B2, L5, `ERR_SCOPE` if exceeded).
    pub max_loop_iterations: NonZeroU32,
    /// Error codes individually downgraded to warnings by the user, at their own
    /// risk (§15). Default: none, every code is blocking.
    pub warnings: WarningCodes,
}

/// Default loop limit (L5).
pub const DEFAULT_MAX_LOOP_ITERATIONS: NonZeroU32 = NonZeroU32::MIN.saturating_add(999);

impl Default for ParserConfig {
    fn default() -> Self {
        Self {
            max_dsp_depth: DEFAULT_MAX_DSP_DEPTH,
            max_loop_iterations: DEFAULT_MAX_LOOP_ITERATIONS,
            warnings: WarningCodes::NONE,
        }
    }
}

/// Syntactic position of the block about to be parsed.
#[derive(Clone, Copy)]
enum Site {
    Head,
    Subordination(Spanned<ColonRun>),
    Coordination {
        conj: Spanned<Conjunction>,
        colons: Option<Spanned<ColonRun>>,
    },
    /// Connector already diagnosed (e.g. too many `:`): the block is parsed
    /// only to collect diagnostics.
    Invalid,
}

impl Site {
    const fn allows_portability(self) -> bool {
        matches!(self, Self::Subordination(_) | Self::Invalid)
    }
}

enum Parsed {
    Clause(ClauseBlock),
    Portability(PortabilityBlock),
}

pub struct Parser<'t, 'src, 'i> {
    tokens: &'t [RawToken<'src>],
    pos: usize,
    interner: &'i mut Interner,
    config: ParserConfig,
    end: Span,
    diagnostics: Vec<Diagnostic>,
}

impl<'t, 'src, 'i> Parser<'t, 'src, 'i> {
    pub fn new(
        tokens: &'t [RawToken<'src>],
        interner: &'i mut Interner,
        config: ParserConfig,
        end: Span,
    ) -> Self {
        Self {
            tokens,
            pos: 0,
            interner,
            config,
            end,
            diagnostics: Vec::new(),
        }
    }

    pub fn into_diagnostics(self) -> Vec<Diagnostic> {
        self.diagnostics
    }

    // ───────────────────────── Cursor ─────────────────────────

    fn peek(&self) -> Option<RawToken<'src>> {
        self.tokens.get(self.pos).copied()
    }

    fn bump(&mut self) -> Option<RawToken<'src>> {
        let token = self.peek();
        if token.is_some() {
            self.pos = self.pos.saturating_add(1);
        }
        token
    }

    fn report(&mut self, kind: DiagnosticKind, span: Span) {
        self.diagnostics.push(Diagnostic::new(kind, span));
    }

    /// `true` if a diagnostic reported after `before` is blocking (§15).
    fn blocking_since(&self, before: usize) -> bool {
        self.diagnostics
            .iter()
            .skip(before)
            .any(|d| self.config.warnings.severity(&d.kind) == Severity::Error)
    }

    // ───────────────────────── Session ─────────────────────────

    /// `session = period { SP period }`.
    /// `has_antecedent`: an antecedent period not closed by `^^/` exists (Q23, D5, R12).
    pub fn parse_session(&mut self, has_antecedent: bool) -> Vec<Period> {
        let mut periods = Vec::new();
        let mut antecedent = has_antecedent;

        if self.tokens.is_empty() {
            self.report(
                DiagnosticKind::UnexpectedEnd {
                    expected: Expected::PeriodOpen,
                },
                self.end,
            );
            return periods;
        }

        while let Some(token) = self.peek() {
            let Some(open) = tiles::period_open(token.text) else {
                self.report(DiagnosticKind::MissingPeriodOpen, token.span);
                self.skip_to_period_open();
                continue;
            };
            self.bump();
            if !antecedent && open != PeriodOpen::Standard {
                self.report(
                    DiagnosticKind::SynchronizedOpenWithoutAntecedent,
                    token.span,
                );
            }
            let (period, close) = self.parse_period(Spanned::new(open, token.span));
            // R12: `^^/` closes the session; a period without a recognized close
            // is already diagnosed and does not alter the synchronization state.
            antecedent = close != Some(PeriodClose::Hard);
            if let Some(period) = period {
                periods.push(period);
            }
        }
        periods
    }

    fn skip_to_period_open(&mut self) {
        while let Some(token) = self.peek() {
            if tiles::period_open(token.text).is_some() {
                break;
            }
            self.bump();
        }
    }

    /// Returns the period (if free of diagnostics) and the kind of close that was read.
    fn parse_period(&mut self, open: Spanned<PeriodOpen>) -> (Option<Period>, Option<PeriodClose>) {
        let before = self.diagnostics.len();

        let head = match self.parse_clause(Site::Head) {
            Some(Parsed::Clause(block)) => Some(block),
            // Portability in head position has already been diagnosed (ERR_SCOPE).
            Some(Parsed::Portability(_)) | None => None,
        };

        let mut tail = Vec::new();
        let close = loop {
            let Some(token) = self.peek() else {
                self.report(DiagnosticKind::MissingPeriodClose, self.end);
                break None;
            };
            if let Some(close) = tiles::period_close(token.text) {
                self.bump();
                break Some(Spanned::new(close, token.span));
            }
            if tiles::period_open(token.text).is_some() {
                self.report(DiagnosticKind::MissingPeriodClose, token.span);
                break None;
            }

            let site = if let Some(count) = tiles::colon_run(token.text) {
                self.bump();
                self.colon_run(count, token.span)
                    .map_or(Site::Invalid, Site::Subordination)
            } else if let Some(conj) = tiles::conjunction(token.text) {
                self.bump();
                let conj = Spanned::new(conj, token.span);
                match self.peek() {
                    Some(next) => match tiles::colon_run(next.text) {
                        Some(count) => {
                            self.bump();
                            match self.colon_run(count, next.span) {
                                Some(colons) => Site::Coordination {
                                    conj,
                                    colons: Some(colons),
                                },
                                None => Site::Invalid,
                            }
                        }
                        None => Site::Coordination { conj, colons: None },
                    },
                    None => Site::Coordination { conj, colons: None },
                }
            } else {
                // Progress guarantee: the block parser stops only on reserved tokens
                // or conjunctions, so this branch reports an orphan token.
                self.report(
                    DiagnosticKind::UnexpectedToken {
                        expected: Expected::CaseTileLinkOrClose,
                    },
                    token.span,
                );
                self.bump();
                continue;
            };

            match (site, self.parse_clause(site)) {
                (Site::Subordination(colons), Some(Parsed::Clause(block))) => {
                    tail.push(LinkedClause::Clause {
                        link: Spanned::new(Link::Subordination(colons.node), colons.span),
                        block,
                    });
                }
                (Site::Subordination(colons), Some(Parsed::Portability(block))) => {
                    tail.push(LinkedClause::Portability { colons, block });
                }
                (Site::Coordination { conj, colons }, Some(Parsed::Clause(block))) => {
                    tail.push(LinkedClause::Clause {
                        link: Spanned::new(Link::Coordination { conj, colons }, conj.span),
                        block,
                    });
                }
                // Misplaced portability (already diagnosed), invalid connector
                // or block with errors: nothing to add.
                _ => {}
            }
        };

        let close_kind = close.map(|c| c.node);
        if self.diagnostics.len() != before {
            return (None, close_kind);
        }
        let period = match (head, close) {
            (Some(head), Some(close)) => Some(Period {
                open,
                head,
                tail,
                close,
            }),
            _ => None,
        };
        (period, close_kind)
    }

    /// Validates a sequence of `:` against the depth limit (Q13).
    fn colon_run(&mut self, count: usize, span: Span) -> Option<Spanned<ColonRun>> {
        let run = u8::try_from(count)
            .ok()
            .and_then(NonZeroU8::new)
            .filter(|c| *c <= self.config.max_dsp_depth);
        match run {
            Some(c) => Some(Spanned::new(ColonRun::new(c), span)),
            None => {
                self.report(
                    DiagnosticKind::LimitExceeded {
                        limit: Limit::DspDepth,
                    },
                    span,
                );
                None
            }
        }
    }

    // ───────────────────────── Blocks ─────────────────────────

    fn parse_clause(&mut self, site: Site) -> Option<Parsed> {
        let before = self.diagnostics.len();

        let Some(signal_token) = self.peek() else {
            self.report(
                DiagnosticKind::UnexpectedEnd {
                    expected: Expected::SignalTile,
                },
                self.end,
            );
            return None;
        };
        if tiles::is_reserved(signal_token.text) {
            self.report(
                DiagnosticKind::UnexpectedToken {
                    expected: Expected::SignalTile,
                },
                signal_token.span,
            );
            return None;
        }
        self.bump();

        if let Err(kind) = tiles::check_tile_characters(signal_token.text) {
            self.report(kind, signal_token.span);
            self.recover_block_body(signal_token.span);
            return None;
        }

        if let Some(keyword) = tiles::portability_keyword(signal_token.text) {
            return self.parse_portability(keyword, signal_token.span, site);
        }

        match tiles::parse_signal(signal_token.text) {
            Err(kind) => {
                self.report(kind, signal_token.span);
                self.recover_block_body(signal_token.span);
                None
            }
            Ok(SignalParse::Relational(signal)) => {
                let glyph = self.signal_glyph(signal_token.span);
                let cases = self.parse_case_pairs();
                let (Some(glyph), Some(cases)) = (glyph, cases) else {
                    return None;
                };
                let block = RelationalBlock {
                    signal: Pair {
                        tile: Spanned::new(signal, signal_token.span),
                        glyph,
                    },
                    cases,
                };
                validate::relational(&block, &mut self.diagnostics);
                // §15: a block is kept when its diagnostics are only downgraded ones.
                (!self.blocking_since(before))
                    .then_some(Parsed::Clause(ClauseBlock::Relational(block)))
            }
            Ok(SignalParse::Def(signal)) => {
                let glyph = self.signal_glyph(signal_token.span);
                let cases = self.parse_case_pairs();
                let (Some(glyph), Some(cases)) = (glyph, cases) else {
                    return None;
                };
                validate::definition(
                    Spanned::new(signal, signal_token.span),
                    glyph,
                    cases,
                    &mut self.diagnostics,
                )
                .map(|block| Parsed::Clause(ClauseBlock::Definition(block)))
            }
        }
    }

    /// After an invalid signal tile, continues positionally to collect
    /// the diagnostics of the rest of the block.
    fn recover_block_body(&mut self, signal_span: Span) {
        let _glyph = self.signal_glyph(signal_span);
        let _cases = self.parse_case_pairs();
    }

    fn parse_glyph(&mut self, token: RawToken<'src>) -> Option<Spanned<GlyphSlot>> {
        match parse_glyph_slot(token.text, self.interner) {
            Ok(slot) => Some(Spanned::new(slot, token.span)),
            Err(kind) => {
                self.report(kind, token.span);
                None
            }
        }
    }

    /// Glyph following a tile: same rule for every pair. If it is missing (end
    /// of input), `missing` is emitted on the tile.
    fn paired_glyph(
        &mut self,
        tile_span: Span,
        missing: DiagnosticKind,
    ) -> Option<Spanned<GlyphSlot>> {
        // Slot Locking (v4.1): any token in an even slot is a glyph, period
        // delimiters and `:` included; a glyph is missing only at the end of input.
        match self.peek() {
            Some(token) => {
                self.bump();
                self.parse_glyph(token)
            }
            None => {
                self.report(missing, tile_span);
                None
            }
        }
    }

    /// Glyph of the signal pair (Q8: `SignalTileWithoutGlyph` if missing).
    fn signal_glyph(&mut self, signal_span: Span) -> Option<Spanned<GlyphSlot>> {
        self.paired_glyph(signal_span, DiagnosticKind::SignalTileWithoutGlyph)
    }

    /// `[case] [glyph]` pairs up to a reserved token or a conjunction
    /// (conjunctions are recognized only in odd slots: in even slots they are glyphs).
    fn parse_case_pairs(&mut self) -> Option<Vec<Pair<CaseTile>>> {
        let before = self.diagnostics.len();
        let mut pairs = Vec::new();

        while let Some(case_token) = self.peek() {
            if tiles::is_reserved(case_token.text) || tiles::conjunction(case_token.text).is_some()
            {
                break;
            }
            self.bump();

            let case = match tiles::check_tile_characters(case_token.text).and_then(|()| {
                tiles::parse_case(case_token.text).ok_or(DiagnosticKind::UnknownCaseTile)
            }) {
                Ok(tile) => Some(Spanned::new(tile, case_token.span)),
                Err(kind) => {
                    self.report(kind, case_token.span);
                    None
                }
            };

            // M§7: case tile not followed by a glyph → ERR_CASE_AMBIGUITY (reported
            // only if the tile is valid, to avoid duplicating diagnostics).
            let glyph = match case {
                Some(_) => self.paired_glyph(case_token.span, DiagnosticKind::CaseTileWithoutGlyph),
                None => match self.peek() {
                    Some(token) => {
                        self.bump();
                        self.parse_glyph(token)
                    }
                    None => None,
                },
            };

            if let (Some(tile), Some(glyph)) = (case, glyph) {
                pairs.push(Pair { tile, glyph });
            }
        }

        (self.diagnostics.len() == before).then_some(pairs)
    }

    /// Q6: `anchor|anchorrel|rel|reloff <GlyphPath>` or `end ~`.
    fn parse_portability(
        &mut self,
        keyword: PortabilityKeyword,
        keyword_span: Span,
        site: Site,
    ) -> Option<Parsed> {
        let before = self.diagnostics.len();
        if !site.allows_portability() {
            self.report(
                DiagnosticKind::PortabilityOutsideSubordination,
                keyword_span,
            );
        }

        let operand = match self.peek() {
            Some(token) => {
                self.bump();
                Some(token)
            }
            None => {
                self.report(DiagnosticKind::SignalTileWithoutGlyph, keyword_span);
                None
            }
        };

        let block =
            operand.and_then(|token| self.portability_operand(keyword, keyword_span, token));

        if let Some(next) = self.peek() {
            if !tiles::is_reserved(next.text) && tiles::conjunction(next.text).is_none() {
                self.report(DiagnosticKind::PortabilityWithCasePairs, next.span);
                let _skipped = self.parse_case_pairs();
            }
        }

        if self.diagnostics.len() != before {
            return None;
        }
        block.map(Parsed::Portability)
    }

    fn portability_operand(
        &mut self,
        keyword: PortabilityKeyword,
        keyword_span: Span,
        token: RawToken<'src>,
    ) -> Option<PortabilityBlock> {
        type Build = fn(Span, Spanned<GlyphPath>) -> PortabilityBlock;
        let build: Build = match keyword {
            PortabilityKeyword::End => return self.end_operand(keyword_span, token),
            PortabilityKeyword::Anchor => |keyword, id| PortabilityBlock::Anchor { keyword, id },
            PortabilityKeyword::AnchorRel => {
                |keyword, id| PortabilityBlock::AnchorRel { keyword, id }
            }
            PortabilityKeyword::Rel => |keyword, id| PortabilityBlock::Rel { keyword, id },
            PortabilityKeyword::RelOff => |keyword, id| PortabilityBlock::RelOff { keyword, id },
        };

        let path = match parse_glyph_slot(token.text, self.interner) {
            Ok(GlyphSlot::Glyph(path)) => path,
            Ok(_) => {
                self.report(DiagnosticKind::PortabilityOperandInvalid, token.span);
                return None;
            }
            Err(kind) => {
                self.report(kind, token.span);
                return None;
            }
        };
        Some(build(keyword_span, Spanned::new(path, token.span)))
    }

    /// `end ~`: the operand must be exactly the `~` anaphora.
    fn end_operand(
        &mut self,
        keyword_span: Span,
        token: RawToken<'src>,
    ) -> Option<PortabilityBlock> {
        if token.text.len() == ANAPHORA_MARK.len_utf8() && token.text.starts_with(ANAPHORA_MARK) {
            Some(PortabilityBlock::End {
                keyword: keyword_span,
                tilde: token.span,
            })
        } else {
            self.report(DiagnosticKind::EndRequiresTilde, token.span);
            None
        }
    }
}
