//! Labels (v4.1): free tokens of the local DTI that are **not** glyphs.
//!
//! - **The Glyph / Label choice is mandatory and deterministic.** In the editor,
//!   a form that the local DTI holds as a label (alone, or together with a
//!   glyph) is written only after the user has selected **Glyph** or **Label**
//!   from the menu; the choice is recorded per slot in the session
//!   ([`Session::set_slot_kind`]). In programmatic or CLI flows without an
//!   interactive selection, a slot that is not marked as a label is a glyph.
//!   There is therefore no "glyph or label" ambiguity at stage 3.
//! - A slot marked as a label is an inert string: the protocol never reads its
//!   content. Two identical labels that denote different real-world objects
//!   are not a conflict for the protocol: the context belongs to sender and
//!   receiver, and the wire carries the same string `LVAAAA<form>` anyway.
//! - In the indexed wire form a glyph travels as its DTI key(s), a label as
//!   `LVA` + a 3-letter subtype `[A-Z]{3}` + the form: `LVAAAA<form>` (`AAA` =
//!   base subtype). DTI keys are lowercase, so a token starting with the
//!   uppercase prefix `LVA` is never a key: the receiver always treats it as a
//!   label, even when the form is absent from its own DTI, and reports a
//!   homonymy when the form is also a glyph of its DTI.
//! - The subtype is generated by the sending machine, never typed by a user. A
//!   subtype other than `AAA` is accepted as a valid label: the receiver
//!   registers it dynamically in its session ([`Session::register_label_subtype`])
//!   and keeps the 3 characters when it re-renders the message in indexed form.
//!   Only a truncated or corrupted token (shorter than 7 characters, subtype
//!   not `[A-Z]{3}`) is malformed.

use crate::prelude::*;

use core::fmt;

use crate::analyze::SlotRef;
use crate::ast::QUALIFIER_SEPARATOR;
use crate::dti::{Dti, FormResolution};
use crate::session::{Session, SlotKind};

use super::resolve::numeral;

/// Wire prefix of a label.
pub const LABEL_PREFIX: &str = "LVA";
/// Subtype code of the base label type.
pub const LABEL_BASE_TYPE: &str = "AAA";
/// Subtype code of the base label type, as bytes.
pub const LABEL_BASE_CODE: [u8; 3] = *b"AAA";
/// Length in bytes of the subtype code that follows [`LABEL_PREFIX`].
pub const LABEL_TYPE_LENGTH: usize = 3;
/// Shortest well-formed wire label: prefix, subtype and a 1-byte form.
pub const MIN_WIRE_LABEL_LENGTH: usize = 7;

/// `true` when the form is a known glyph of the DTI: a primary form (the whole
/// token first, `§` included), a numeral, or a `§` union of known segments.
pub fn is_glyph_form(dti: &Dti, form: &str) -> bool {
    let known = |text: &str| {
        !matches!(dti.resolve_primary(text), FormResolution::Unknown)
            || numeral(dti, text).is_some()
    };
    known(form)
        || (form.contains(QUALIFIER_SEPARATOR)
            && form
                .split(QUALIFIER_SEPARATOR)
                .all(|segment| !segment.is_empty() && known(segment)))
}

/// How the glyph token of a slot is transmitted.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum SlotContent {
    /// A glyph: resolved through the DTI.
    Glyph,
    /// A slot marked as a label by the user: `LVAAAA<form>`.
    Label,
    /// A token already in wire-label form (`LVA<XYZ><form>`, machine
    /// generated, e.g. received): kept verbatim, subtype included.
    WireLabel,
}

/// Deterministic classification of the glyph token `text` held by `slot`: a
/// well-formed wire label, then the user's choice; unmarked slots are glyphs.
pub(crate) fn slot_content(session: &Session, slot: SlotRef, text: &str) -> SlotContent {
    if matches!(parse_label_wire(text), Some(Ok(_))) {
        return SlotContent::WireLabel;
    }
    match session.effective_slot_kind(slot) {
        SlotKind::Label => SlotContent::Label,
        SlotKind::Glyph => SlotContent::Glyph,
    }
}

/// Wire form of a label of the base subtype: `LVAAAA<form>`.
pub fn label_wire(form: &str) -> String {
    let mut out = String::with_capacity(
        LABEL_PREFIX
            .len()
            .saturating_add(LABEL_BASE_TYPE.len())
            .saturating_add(form.len()),
    );
    out.push_str(LABEL_PREFIX);
    out.push_str(LABEL_BASE_TYPE);
    out.push_str(form);
    out
}

/// Subtype of a received label.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LabelSubtype {
    /// `AAA`, or a subtype already registered in the session.
    Known([u8; 3]),
    /// A subtype seen for the first time: accepted as a valid label and
    /// registered by [`super::receive_indexed_input`].
    Dynamic([u8; 3]),
}

impl LabelSubtype {
    /// The 3-letter code.
    pub const fn code(self) -> [u8; 3] {
        match self {
            Self::Known(code) | Self::Dynamic(code) => code,
        }
    }
}

/// A token starts with [`LABEL_PREFIX`] but is truncated or corrupted: shorter
/// than [`MIN_WIRE_LABEL_LENGTH`] bytes, or its subtype is not `[A-Z]{3}`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MalformedLabel;

impl fmt::Display for MalformedLabel {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("malformed label token (expected LVA<[A-Z]{3}><form>)")
    }
}

impl core::error::Error for MalformedLabel {}

/// A label token read from the indexed wire form.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WireLabel<'a> {
    /// 3-letter subtype code (`AAA` = base subtype).
    pub code: [u8; 3],
    pub form: &'a str,
}

/// Splits a wire token starting with [`LABEL_PREFIX`]; `None` for any other
/// token.
pub fn parse_label_wire(token: &str) -> Option<Result<WireLabel<'_>, MalformedLabel>> {
    let rest = token.strip_prefix(LABEL_PREFIX)?;
    if token.len() < MIN_WIRE_LABEL_LENGTH {
        return Some(Err(MalformedLabel));
    }
    let (Some(code), Some(form)) = (rest.get(..LABEL_TYPE_LENGTH), rest.get(LABEL_TYPE_LENGTH..))
    else {
        return Some(Err(MalformedLabel));
    };
    let Ok(code) = <[u8; 3]>::try_from(code.as_bytes()) else {
        return Some(Err(MalformedLabel));
    };
    if !code.iter().all(u8::is_ascii_uppercase) || form.is_empty() {
        return Some(Err(MalformedLabel));
    }
    Some(Ok(WireLabel { code, form }))
}
