//! Copy with anchors (v4.1, §9.5): the selected subordinate clauses are copied
//! as a portability block, ready to be pasted elsewhere.
//!
//! - [`CopyMode::Absolute`] (`Ctrl+C`): `<:…> anchor <id> <clauses> <:…> end ~`,
//!   the colon runs of the clauses are kept as written (absolute depths);
//! - [`CopyMode::Relative`] (`Alt+C` with a selection): `<:…> anchorrel <id>
//!   <clauses> : end ~`, the colon runs are rewritten relative to the
//!   shallowest selected clause, which gets a single `:` (depth of the anchor).
//!
//! The anchor is written with the colon run of the shallowest selected clause,
//! so the block pasted in place denotes the same tree. The selection must hold
//! whole clauses of canonical text, the first one introduced by a colon run
//! (a subordinate); a clause may also be introduced by a conjunction. Slot
//! Locking is respected: a colon run in an even slot is a glyph.

use std::fmt;
use std::ops::Range;

use crate::ast::{ANAPHORA_MARK, SEMA_ANAPHORA_MARK};
use crate::stage3::LABEL_PREFIX;
use crate::tiles;

/// Prefix of the anchor ids generated by [`copy_subordinates`].
pub const GENERATED_ID_PREFIX: &str = "copy";

/// Kind of anchor of the copied block.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CopyMode {
    /// `anchor`: absolute depths (`Ctrl+C`).
    Absolute,
    /// `anchorrel`: depths relative to the anchor (`Alt+C`).
    Relative,
}

/// Why a selection cannot be copied.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CopyError {
    /// Nothing is selected.
    EmptySelection,
    /// The selection is outside the text or not on character boundaries.
    InvalidSelection,
    /// The selection does not start with a colon run (it is not a subordinate).
    NotSubordinate,
    /// The selection ends in the middle of a clause, or a clause has no glyph.
    IncompleteClause,
    /// The id is empty, contains whitespace or invisible characters, starts
    /// with the label prefix, or is the operator `~` / `~~`.
    InvalidId { id: String },
}

impl fmt::Display for CopyError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptySelection => f.write_str("nothing is selected"),
            Self::InvalidSelection => f.write_str("the selection is not a valid range of the text"),
            Self::NotSubordinate => {
                f.write_str("the selection must start with a colon run (a subordinate clause)")
            }
            Self::IncompleteClause => f.write_str("the selection must hold whole clauses"),
            Self::InvalidId { id } => write!(f, "'{id}' is not a valid anchor id"),
        }
    }
}

impl std::error::Error for CopyError {}

/// Result of a copy: the portability block and the anchor id it uses.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CopiedBlock {
    pub text: String,
    pub id: String,
}

/// One selected clause: optional conjunction, optional colon count, then the
/// tokens of its pairs.
struct Clause<'a> {
    conjunction: Option<&'a str>,
    colons: Option<usize>,
    pairs: Vec<&'a str>,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Expect {
    /// Conjunction or colon run (start of a clause).
    Connector,
    /// Colon run or signal tile, right after a conjunction.
    AfterConjunction,
    /// Signal tile (odd slot).
    Signal,
    /// Glyph (even slot).
    Glyph,
    /// Case tile or connector (odd slot after a pair).
    AfterPair,
}

fn split_clauses(selection: &str) -> Result<Vec<Clause<'_>>, CopyError> {
    let mut clauses: Vec<Clause<'_>> = Vec::new();
    let mut expect = Expect::Connector;
    for token in selection.split_whitespace() {
        match expect {
            Expect::Glyph => {
                if let Some(clause) = clauses.last_mut() {
                    clause.pairs.push(token);
                }
                expect = Expect::AfterPair;
            }
            Expect::Signal => {
                if let Some(clause) = clauses.last_mut() {
                    clause.pairs.push(token);
                }
                expect = Expect::Glyph;
            }
            Expect::Connector | Expect::AfterPair | Expect::AfterConjunction => {
                if let Some(count) = tiles::colon_run(token) {
                    match (expect, clauses.last_mut()) {
                        (Expect::AfterConjunction, Some(clause)) => {
                            clause.colons = Some(count);
                        }
                        _ => clauses.push(Clause {
                            conjunction: None,
                            colons: Some(count),
                            pairs: Vec::new(),
                        }),
                    }
                    expect = Expect::Signal;
                } else if expect != Expect::AfterConjunction && tiles::conjunction(token).is_some()
                {
                    if clauses.is_empty() {
                        return Err(CopyError::NotSubordinate);
                    }
                    clauses.push(Clause {
                        conjunction: Some(token),
                        colons: None,
                        pairs: Vec::new(),
                    });
                    expect = Expect::AfterConjunction;
                } else if expect == Expect::AfterConjunction {
                    // A conjunction without a colon run: the signal tile follows.
                    if let Some(clause) = clauses.last_mut() {
                        clause.pairs.push(token);
                    }
                    expect = Expect::Glyph;
                } else if expect == Expect::AfterPair {
                    // Case tile of the current clause.
                    if let Some(clause) = clauses.last_mut() {
                        clause.pairs.push(token);
                    }
                    expect = Expect::Glyph;
                } else {
                    return Err(CopyError::NotSubordinate);
                }
            }
        }
    }
    match expect {
        Expect::AfterPair => Ok(clauses),
        Expect::Connector => Err(CopyError::EmptySelection),
        Expect::AfterConjunction | Expect::Signal | Expect::Glyph => {
            Err(CopyError::IncompleteClause)
        }
    }
}

fn check_id(id: &str) -> Result<(), CopyError> {
    let invalid = id.is_empty()
        || id == SEMA_ANAPHORA_MARK
        || id.strip_prefix(ANAPHORA_MARK) == Some("")
        || id.starts_with(LABEL_PREFIX)
        || id
            .chars()
            .any(|c| c.is_whitespace() || c.is_control() || is_format(c));
    if invalid {
        Err(CopyError::InvalidId { id: id.to_owned() })
    } else {
        Ok(())
    }
}

/// Format/bidi characters refused by D9.
const fn is_format(ch: char) -> bool {
    matches!(
        ch,
        '\u{061C}'
            | '\u{200B}'..='\u{200F}'
            | '\u{202A}'..='\u{202E}'
            | '\u{2060}'..='\u{2064}'
            | '\u{2066}'..='\u{2069}'
            | '\u{FEFF}'
    )
}

/// First `copy<N>` (N ≥ 1) that is not a token of `text`.
fn generate_id(text: &str) -> String {
    let used: Vec<&str> = text.split_whitespace().collect();
    let mut n: u64 = 1;
    loop {
        let candidate = format!("{GENERATED_ID_PREFIX}{n}");
        if !used.contains(&candidate.as_str()) {
            return candidate;
        }
        n = n.saturating_add(1);
    }
}

/// Copies the subordinate clauses selected in `text` (byte range `selection`)
/// as an anchor block (see the module documentation). `id` is the anchor id;
/// when `None`, the first `copy<N>` absent from `text` is generated.
pub fn copy_subordinates(
    text: &str,
    selection: Range<usize>,
    mode: CopyMode,
    id: Option<&str>,
) -> Result<CopiedBlock, CopyError> {
    if selection.is_empty() {
        return Err(CopyError::EmptySelection);
    }
    let selected = text.get(selection).ok_or(CopyError::InvalidSelection)?;
    let clauses = split_clauses(selected)?;
    let id = match id {
        Some(id) => {
            check_id(id)?;
            id.to_owned()
        }
        None => generate_id(text),
    };
    let shallowest = clauses
        .iter()
        .filter_map(|clause| clause.colons)
        .min()
        .ok_or(CopyError::NotSubordinate)?;
    let keyword = match mode {
        CopyMode::Absolute => "anchor",
        CopyMode::Relative => "anchorrel",
    };
    let opening = ":".repeat(shallowest);
    let mut tokens: Vec<&str> = vec![&opening, keyword, &id];
    let runs: Vec<Option<String>> = clauses
        .iter()
        .map(|clause| {
            clause.colons.map(|colons| match mode {
                CopyMode::Absolute => ":".repeat(colons),
                CopyMode::Relative => {
                    ":".repeat(colons.saturating_sub(shallowest).saturating_add(1))
                }
            })
        })
        .collect();
    for (clause, run) in clauses.iter().zip(&runs) {
        if let Some(conjunction) = clause.conjunction {
            tokens.push(conjunction);
        }
        if let Some(run) = run {
            tokens.push(run);
        }
        tokens.extend(clause.pairs.iter().copied());
    }
    let closing = match mode {
        CopyMode::Absolute => opening.as_str(),
        CopyMode::Relative => ":",
    };
    let marker = ANAPHORA_MARK.to_string();
    tokens.extend([closing, "end", marker.as_str()]);
    let text = tokens.join(" ");
    Ok(CopiedBlock { text, id })
}
